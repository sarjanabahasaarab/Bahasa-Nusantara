import { AdaptorPlatformGUI, TipePlatformGUI } from './adapter';
import { KonfigurasiAplikasiGUI } from '../types';
import { JendelaGUI } from '../core/window';
import { DetektorPlatformDesktop, StatusPlatformDesktop } from './detector';
import { AdaptorHeadlessGUI } from './headless';
import { muatModulNode } from './node_bridge';

export interface HasilEksekusiNativeWindow {
  status: 'NATIVE_LAUNCHED' | 'NATIVE_DISPLAY_UNAVAILABLE' | 'TOOLCHAIN_NOT_INSTALLED';
  platform: TipePlatformGUI;
  pesan: string;
  berkasHost?: string;
}

export abstract class AdaptorDesktopNativeDasar implements AdaptorPlatformGUI {
  protected konfig?: KonfigurasiAplikasiGUI;
  protected jendelaTerbuka: Map<string, JendelaGUI> = new Map();
  protected prosesAktif: Map<string, any> = new Map();
  protected laporanTerakhir?: HasilEksekusiNativeWindow;

  public abstract dapatkanNamaPlatform(): TipePlatformGUI;
  public abstract hasilkanSumberHostNative(jendela: JendelaGUI): { namaBerkas: string; isi: string; bahasa: string };
  protected abstract luncurkanJendelaOS(jendela: JendelaGUI, status: StatusPlatformDesktop): Promise<HasilEksekusiNativeWindow>;

  public dapatkanLaporanTerakhir(): HasilEksekusiNativeWindow | undefined {
    return this.laporanTerakhir;
  }

  public async inisialisasi(konfig: KonfigurasiAplikasiGUI): Promise<void> {
    this.konfig = konfig;
  }

  public async bukaJendela(jendela: JendelaGUI): Promise<void> {
    this.jendelaTerbuka.set(jendela.id, jendela);
    const status = DetektorPlatformDesktop.deteksi();
    this.laporanTerakhir = await this.luncurkanJendelaOS(jendela, status);
  }

  public async tutupJendela(id: string): Promise<void> {
    const proc = this.prosesAktif.get(id);
    if (proc && typeof proc.kill === 'function') {
      try {
        proc.kill();
      } catch {
        // ignore
      }
      this.prosesAktif.delete(id);
    }
    this.jendelaTerbuka.delete(id);
  }

  public async perbaruiTampilan(jendela: JendelaGUI): Promise<void> {
    const proc = this.prosesAktif.get(jendela.id);
    if (proc && proc.stdin && !proc.stdin.destroyed) {
      proc.stdin.write(JSON.stringify(jendela.serialisasi()) + '\n');
    }
  }

  public async hancurkan(): Promise<void> {
    for (const id of Array.from(this.jendelaTerbuka.keys())) {
      await this.tutupJendela(id);
    }
  }
}

export class AdaptorDesktopLinux extends AdaptorDesktopNativeDasar {
  public dapatkanNamaPlatform(): TipePlatformGUI {
    return 'linux';
  }

  public hasilkanSumberHostNative(jendela: JendelaGUI): { namaBerkas: string; isi: string; bahasa: string } {
    const judulAman = jendela.judul.replace(/"/g, '\\"');
    return {
      namaBerkas: 'nusantara_linux_host.c',
      bahasa: 'c-gtk3',
      isi: `/* Generated by NUSANTARA GUI Framework (Phase 36) */
#include <gtk/gtk.h>

static void aktifkan(GtkApplication *app, gpointer user_data) {
  GtkWidget *window = gtk_application_window_new(app);
  gtk_window_set_title(GTK_WINDOW(window), "${judulAman}");
  gtk_window_set_default_size(GTK_WINDOW(window), ${Math.round(jendela.lebar)}, ${Math.round(jendela.tinggi)});
  GtkWidget *label = gtk_label_new("NUSANTARA Desktop Window Ready");
  gtk_container_add(GTK_CONTAINER(window), label);
  gtk_widget_show_all(window);
}

int main(int argc, char **argv) {
  GtkApplication *app = gtk_application_new("${this.konfig?.idAplikasi || 'id.nusantara.desktop'}", G_APPLICATION_DEFAULT_FLAGS);
  g_signal_connect(app, "activate", G_CALLBACK(aktifkan), NULL);
  int status = g_application_run(G_APPLICATION(app), argc, argv);
  g_object_unref(app);
  return status;
}
`,
    };
  }

  protected async luncurkanJendelaOS(
    jendela: JendelaGUI,
    status: StatusPlatformDesktop
  ): Promise<HasilEksekusiNativeWindow> {
    if (!status.displayAktif) {
      return {
        status: 'NATIVE_DISPLAY_UNAVAILABLE',
        platform: 'linux',
        pesan: `${status.detailDisplay} Peluncuran jendela X11/Wayland dilewati secara jujur.`,
      };
    }

    const fs = muatModulNode<any>('fs');
    const os = muatModulNode<any>('os');
    const path = muatModulNode<any>('path');
    const cp = muatModulNode<any>('child_process');
    if (!fs || !os || !path || !cp) {
      return {
        status: 'TOOLCHAIN_NOT_INSTALLED',
        platform: 'linux',
        pesan: 'API proses OS Node.js tidak tersedia.',
      };
    }

    if (status.perkakas.gcc && status.perkakas.gtk3) {
      const dirTmp = fs.mkdtempSync(path.join(os.tmpdir(), 'nusantara-gui-'));
      const sumber = this.hasilkanSumberHostNative(jendela);
      const pathC = path.join(dirTmp, sumber.namaBerkas);
      const pathBin = path.join(dirTmp, 'nusantara_host');
      fs.writeFileSync(pathC, sumber.isi, 'utf-8');
      const flags = cp.execSync('pkg-config --cflags --libs gtk+-3.0', { encoding: 'utf-8' }).trim().split(/\s+/);
      const comp = cp.spawnSync('gcc', [pathC, '-o', pathBin, ...flags], { encoding: 'utf-8' });
      if (comp.status === 0) {
        const proc = cp.spawn(pathBin, [], { detached: true, stdio: 'pipe' });
        this.prosesAktif.set(jendela.id, proc);
        return {
          status: 'NATIVE_LAUNCHED',
          platform: 'linux',
          pesan: 'Jendela GTK3 Linux native diluncurkan.',
          berkasHost: pathBin,
        };
      }
    }

    if (status.perkakas.tkinter) {
      const pyScript = `import tkinter as tk\nr = tk.Tk()\nr.title(${JSON.stringify(jendela.judul)})\nr.geometry("${Math.round(jendela.lebar)}x${Math.round(jendela.tinggi)}")\nr.mainloop()`;
      const proc = cp.spawn('python3', ['-c', pyScript], { detached: true, stdio: 'pipe' });
      this.prosesAktif.set(jendela.id, proc);
      return {
        status: 'NATIVE_LAUNCHED',
        platform: 'linux',
        pesan: 'Jendela X11 Tkinter Python diluncurkan.',
      };
    }

    return {
      status: 'TOOLCHAIN_NOT_INSTALLED',
      platform: 'linux',
      pesan: status.panduanInstalasi,
    };
  }
}

export class AdaptorDesktopWindows extends AdaptorDesktopNativeDasar {
  public dapatkanNamaPlatform(): TipePlatformGUI {
    return 'windows';
  }

  public hasilkanSumberHostNative(jendela: JendelaGUI): { namaBerkas: string; isi: string; bahasa: string } {
    const judulAman = jendela.judul.replace(/"/g, '\\"');
    return {
      namaBerkas: 'nusantara_win32_host.c',
      bahasa: 'c-win32',
      isi: `/* Generated by NUSANTARA GUI Framework (Phase 36) */
#include <windows.h>

LRESULT CALLBACK WindowProc(HWND hwnd, UINT uMsg, WPARAM wParam, LPARAM lParam) {
  if (uMsg == WM_DESTROY) { PostQuitMessage(0); return 0; }
  return DefWindowProcA(hwnd, uMsg, wParam, lParam);
}

int WINAPI WinMain(HINSTANCE hInstance, HINSTANCE hPrevInstance, LPSTR lpCmdLine, int nCmdShow) {
  const char CLASS_NAME[] = "NusantaraWindowClass";
  WNDCLASSA wc = {0};
  wc.lpfnWndProc = WindowProc;
  wc.hInstance = hInstance;
  wc.lpszClassName = CLASS_NAME;
  RegisterClassA(&wc);
  HWND hwnd = CreateWindowExA(0, CLASS_NAME, "${judulAman}", WS_OVERLAPPEDWINDOW,
    CW_USEDEFAULT, CW_USEDEFAULT, ${Math.round(jendela.lebar)}, ${Math.round(jendela.tinggi)}, NULL, NULL, hInstance, NULL);
  if (!hwnd) return 1;
  ShowWindow(hwnd, nCmdShow);
  MSG msg = {0};
  while (GetMessageA(&msg, NULL, 0, 0) > 0) { TranslateMessage(&msg); DispatchMessageA(&msg); }
  return 0;
}
`,
    };
  }

  protected async luncurkanJendelaOS(
    jendela: JendelaGUI,
    status: StatusPlatformDesktop
  ): Promise<HasilEksekusiNativeWindow> {
    if (status.os !== 'windows') {
      return {
        status: 'NATIVE_DISPLAY_UNAVAILABLE',
        platform: 'windows',
        pesan: `Host bukan Windows (OS saat ini: ${status.os}).`,
      };
    }
    const cp = muatModulNode<any>('child_process');
    if (!cp) {
      return { status: 'TOOLCHAIN_NOT_INSTALLED', platform: 'windows', pesan: 'child_process tidak tersedia.' };
    }
    const psScript = `Add-Type -AssemblyName System.Windows.Forms; $f = New-Object System.Windows.Forms.Form; $f.Text = ${JSON.stringify(jendela.judul)}; $f.Width = ${Math.round(jendela.lebar)}; $f.Height = ${Math.round(jendela.tinggi)}; [void]$f.ShowDialog()`;
    const proc = cp.spawn('powershell', ['-NoProfile', '-Command', psScript], { detached: true, stdio: 'pipe' });
    this.prosesAktif.set(jendela.id, proc);
    return {
      status: 'NATIVE_LAUNCHED',
      platform: 'windows',
      pesan: 'Jendela Win32/WinForms diluncurkan.',
    };
  }
}

export class AdaptorDesktopMacOS extends AdaptorDesktopNativeDasar {
  public dapatkanNamaPlatform(): TipePlatformGUI {
    return 'macos';
  }

  public hasilkanSumberHostNative(jendela: JendelaGUI): { namaBerkas: string; isi: string; bahasa: string } {
    const judulAman = jendela.judul.replace(/"/g, '\\"');
    return {
      namaBerkas: 'NusantaraCocoaHost.swift',
      bahasa: 'swift-appkit',
      isi: `// Generated by NUSANTARA GUI Framework (Phase 36)
import AppKit

let app = NSApplication.shared
app.setActivationPolicy(.regular)
let frame = NSRect(x: 0, y: 0, width: ${Math.round(jendela.lebar)}, height: ${Math.round(jendela.tinggi)})
let window = NSWindow(contentRect: frame, styleMask: [.titled, .closable, .resizable, .miniaturizable], backing: .buffered, defer: false)
window.title = "${judulAman}"
window.center()
window.makeKeyAndOrderFront(nil)
app.activate(ignoringOtherApps: true)
app.run()
`,
    };
  }

  protected async luncurkanJendelaOS(
    jendela: JendelaGUI,
    status: StatusPlatformDesktop
  ): Promise<HasilEksekusiNativeWindow> {
    if (status.os !== 'macos') {
      return {
        status: 'NATIVE_DISPLAY_UNAVAILABLE',
        platform: 'macos',
        pesan: `Host bukan macOS Cocoa (OS saat ini: ${status.os}).`,
      };
    }
    if (!status.perkakas.swiftc) {
      return {
        status: 'TOOLCHAIN_NOT_INSTALLED',
        platform: 'macos',
        pesan: status.panduanInstalasi,
      };
    }
    const fs = muatModulNode<any>('fs');
    const os = muatModulNode<any>('os');
    const path = muatModulNode<any>('path');
    const cp = muatModulNode<any>('child_process');
    const dirTmp = fs.mkdtempSync(path.join(os.tmpdir(), 'nusantara-cocoa-'));
    const sumber = this.hasilkanSumberHostNative(jendela);
    const swiftFile = path.join(dirTmp, sumber.namaBerkas);
    const binFile = path.join(dirTmp, 'NusantaraCocoaHost');
    fs.writeFileSync(swiftFile, sumber.isi, 'utf-8');
    const comp = cp.spawnSync('swiftc', [swiftFile, '-o', binFile], { encoding: 'utf-8' });
    if (comp.status === 0) {
      const proc = cp.spawn(binFile, [], { detached: true, stdio: 'pipe' });
      this.prosesAktif.set(jendela.id, proc);
      return {
        status: 'NATIVE_LAUNCHED',
        platform: 'macos',
        pesan: 'Jendela macOS AppKit/Cocoa native diluncurkan.',
        berkasHost: binFile,
      };
    }
    return {
      status: 'TOOLCHAIN_NOT_INSTALLED',
      platform: 'macos',
      pesan: `Gagal mengompilasi host Cocoa: ${comp.stderr}`,
    };
  }
}

export function buatAdaptorPlatformDesktop(preferensi?: TipePlatformGUI): AdaptorPlatformGUI {
  if (preferensi === 'headless') return new AdaptorHeadlessGUI();
  const os = typeof process !== 'undefined' ? process.platform : 'unknown';
  const target = preferensi || (os === 'linux' ? 'linux' : os === 'win32' ? 'windows' : os === 'darwin' ? 'macos' : 'headless');
  if (target === 'linux') return new AdaptorDesktopLinux();
  if (target === 'windows') return new AdaptorDesktopWindows();
  if (target === 'macos') return new AdaptorDesktopMacOS();
  return new AdaptorHeadlessGUI();
}
